"""Export the Prism instance into the repository and build the .mrpack.

usage: export_pack.py <instance game dir> <repo dir>

Writes <repo>/pack/modrinth.index.json, <repo>/pack/overrides/, MODS.md and docs/hotkeys.html, then <repo>/dist/RedstoneExMachina-<version>.mrpack.
Files tracked by Prism (.pw.toml) become Modrinth downloads; everything listed in OVERRIDES is copied as is.
"""

import glob
import hashlib
import json
import os
import shutil
import sys
import tomllib
import urllib.parse
import zipfile

sys.path.insert(0, os.path.dirname(__file__))
from hotkeys import VERSION, page  # noqa: E402  single version source and hotkey sheet

MINECRAFT, FABRIC_LOADER = '26.2', '0.19.5'

# Copied into the pack as is (relative to the game dir). Config Manager copies config/modpack_defaults
# into the game dir on first launch without overwriting user files.
OVERRIDES = [
    'config/modpack_defaults',
    'config/crash_assistant',
    'config/isxander-main-menu-credits.json',
    'config/fabric_loader_dependencies.json',
    'resourcepacks/Mod Menu Helper.zip',
    'resourcepacks/RedstoneExMachina UI.zip',
    'mods/meteor-client-26.2-35.jar',
    'mods/baritone-meteor-26.2.jar',
]
TRACKED = ['mods/.index/*.pw.toml', 'resourcepacks/.index/*.pw.toml', 'shaderpacks/*.pw.toml']


def digest(path, algorithm):
    h = hashlib.new(algorithm)
    with open(path, 'rb') as f:
        h.update(f.read())
    return h.hexdigest()


def modrinth_files(game):
    """Modrinth download entries plus (folder, name, version, project id) rows for MODS.md."""
    files, rows = [], []
    for pattern in TRACKED:
        for toml_path in sorted(glob.glob(os.path.join(game, pattern))):
            meta = tomllib.load(open(toml_path, 'rb'))
            folder = os.path.relpath(os.path.dirname(toml_path), game).removesuffix('/.index')
            local = os.path.join(game, folder, meta['filename'])
            sha512 = digest(local, 'sha512')
            if sha512 != meta['download']['hash']:
                sys.exit(f'{local}: hash differs from its Prism tracking file')
            files.append({
                'path': f'{folder}/{meta["filename"]}',
                'hashes': {'sha1': digest(local, 'sha1'), 'sha512': sha512},
                'env': {'client': 'required', 'server': 'unsupported'},
                'downloads': [urllib.parse.quote(meta['download']['url'], safe=':/%?=&')],
                'fileSize': os.path.getsize(local),
            })
            rows.append((folder, meta['name'], meta.get('x-prismlauncher-version-number', ''),
                         meta['update']['modrinth']['mod-id']))
    return files, rows


def mods_markdown(rows):
    titles = {'mods': 'Mods', 'resourcepacks': 'Resource packs', 'shaderpacks': 'Shader packs'}
    lines = [f'# RedstoneExMachina {VERSION} contents', '',
             'Generated by `tools/export_pack.py`. Every file below is downloaded from Modrinth at install time.',
             'Meteor Client and Baritone are bundled in the pack (see `NOTICE.md`).']
    for folder, title in titles.items():
        lines += ['', f'## {title}', '', '| Name | Version |', '| --- | --- |']
        lines += [f'| [{name}](https://modrinth.com/project/{pid}) | {version} |'
                  for f, name, version, pid in sorted(rows, key=lambda r: r[1].lower()) if f == folder]
    return '\n'.join(lines) + '\n'


def copy_overrides(game, target):
    shutil.rmtree(target, ignore_errors=True)
    for rel in OVERRIDES:
        src, dst = os.path.join(game, rel), os.path.join(target, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        (shutil.copytree if os.path.isdir(src) else shutil.copy2)(src, dst)


def build_mrpack(pack_dir, out):
    """Zip with a fixed timestamp, so the same pack always gives the same file."""
    os.makedirs(os.path.dirname(out), exist_ok=True)
    paths = [os.path.join(pack_dir, 'modrinth.index.json')] + sorted(
        p for p in glob.glob(os.path.join(pack_dir, 'overrides', '**', '*'), recursive=True) if os.path.isfile(p))
    with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as z:
        for path in paths:
            info = zipfile.ZipInfo(os.path.relpath(path, pack_dir), date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            with open(path, 'rb') as f:
                z.writestr(info, f.read())


def main():
    game, repo = sys.argv[1:3]
    pack_dir = os.path.join(repo, 'pack')
    os.makedirs(pack_dir, exist_ok=True)
    files, rows = modrinth_files(game)
    index = {
        'formatVersion': 1,
        'game': 'minecraft',
        'versionId': VERSION,
        'name': 'RedstoneExMachina',
        'summary': 'Fabric 26.2 pack for technical redstone players, based on Fabulously Optimized.',
        'files': files,
        'dependencies': {'minecraft': MINECRAFT, 'fabric-loader': FABRIC_LOADER},
    }
    with open(os.path.join(pack_dir, 'modrinth.index.json'), 'w') as f:
        f.write(json.dumps(index, indent=2) + '\n')
    with open(os.path.join(repo, 'MODS.md'), 'w') as f:
        f.write(mods_markdown(rows))
    os.makedirs(os.path.join(repo, 'docs'), exist_ok=True)
    with open(os.path.join(repo, 'docs', 'hotkeys.html'), 'w') as f:
        f.write(page())
    copy_overrides(game, os.path.join(pack_dir, 'overrides'))
    out = os.path.join(repo, 'dist', f'RedstoneExMachina-{VERSION}.mrpack')
    build_mrpack(pack_dir, out)
    print(f'{len(index["files"])} Modrinth files, overrides copied, {out}')


if __name__ == '__main__':
    main()
